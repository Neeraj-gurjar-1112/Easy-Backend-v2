async function ensureAdmin() {
  const email = process.env.SEED_ADMIN_EMAIL || DEFAULT_ADMIN_EMAIL;
  const existing = await Admin.findOne({ email });
  if (existing) return { email, created: false };
  await Admin.create({
    email,
    role: "superadmin",
    password: process.env.SEED_ADMIN_PASSWORD || DEFAULT_ADMIN_PASSWORD,
  });
  return { email, created: true };
}

/**
 * Upserts the 32 agents (by email) and makes sure the admin exists.
 * @param {{ reset?: boolean, log?: (msg: string) => void }} options  reset = delete all agents first
 */
async function seedDeliveryAgents({ reset = false, log = () => {} } = {}) {
  if (reset) {
    const { deletedCount } = await DeliveryAgent.deleteMany({});
    log(`Removed ${deletedCount} delivery agents`);
  }

  const admin = await ensureAdmin();
  log(
    admin.created
      ? `Created admin ${admin.email}`
      : `Admin ${admin.email} already exists`,
  );

  let created = 0;
  let updated = 0;
  for (const [
    name,
    email,
    phone,
    vehicle_type,
    approved,
    active,
    available,
    assigned_orders,
    completed_orders,
    rating,
    created_at,
    license_number,
  ] of ROWS) {
    const doc = {
      name,
      email,
      phone,
      vehicle_type,
      approved,
      active,
      available,
      assigned_orders,
      completed_orders,
      rating,
      total_ratings: completed_orders ? Math.round(completed_orders * 0.6) : 0,
      license_number,
      working_hours: { start: "09:00", end: "21:00" },
      created_at: new Date(created_at),
    };
    const result = await DeliveryAgent.updateOne(
      { email },
      { $set: doc },
      { upsert: true, runValidators: true },
    );
    if (result.upsertedCount) created += 1;
    else updated += 1;
  }
  const total = await DeliveryAgent.countDocuments();
  log(
    `Delivery agents: ${created} created, ${updated} updated, ${total} total`,
  );
  return { created, updated, total, admin: admin.email };
}

